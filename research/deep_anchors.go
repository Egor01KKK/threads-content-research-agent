// DeepAnchorBank returns the complete production anchor bank in stable order.
func DeepAnchorBank() []DeepAnchor {
	seen := map[string]bool{}
	var out []DeepAnchor
	position := 0
	for _, group := range deepAnchorGroups {
		for _, query := range group.queries {
			query = normalizeSpace(query)
			key := strings.ToLower(query)
			if query == "" || seen[key] {
				continue
			}
			seen[key] = true
			out = append(out, DeepAnchor{Query: query, Category: group.category, Position: position})
			position++
		}
	}
	return out
}

